/** A text by a composed key (pinType_<type>, paramKind_<kind>); `fallback` when the key is missing. */
export function ptDynamic(key: string, fallback: string, params?: Record<string, string | number>): string {
  const entry = (PLACE_TEXT as Record<string, LocalizedText>)[key];
  return entry ? interpolate(tr(entry), params) : fallback;
}
