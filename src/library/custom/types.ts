/**
 * User-made components (component wizard, symbol editor, database manager, SPICE model import,
 * model makers) — the serialisable data model.
 *
 * CONTRACT FILE (additive changes only). A user component is plain JSON (`CustomPartData`) so it
 * can live in three places with the same shape:
 *   - a part database (`PartDatabase`: the user database and the corporate database, stored in
 *     browser storage on the web and in a user-data file on the desktop, exported / imported as
 *     `.msimdb` JSON files),
 *   - a design file (`Design.customParts`: every user component a design uses is embedded, so the
 *     file opens and simulates on another computer that does not have the database),
 *   - the clipboard / a symbol file (`SymbolFile` holds a symbol alone).
 * `customPartDef(data)` (partDef.ts) turns the data into a library `PartDef` whose `toSpice`
 * builds the simulation elements.
 *
 * Ids: every user component id starts with CUSTOM_PREFIX ('custom:'), e.g. 'custom:my-zener-5v6'.
 * The id never changes when the part moves between databases, so designs keep working.
 *
 * Simulation models (`CustomModel`):
 *   - 'none'     graphic only (connectors, mechanical parts): not simulated.
 *   - 'builtin'  reuses a part of the master (built-in) library: the new symbol's pins are mapped
 *                onto the library part's pins and its parameters are copied (default values may be
 *                changed). Used by "edit a placed part's symbol and save it as a new part" and by
 *                the AC-motor model maker.
 *   - 'spice'    SPICE text with `.model` and / or `.subckt` cards (pasted, imported from a file or
 *                generated by a model maker). `name` selects the card the part uses; `pins[i]` is
 *                the symbol pin wired to model terminal i (subcircuit port i, or the device
 *                terminals in SPICE order: D = A K, BJT = C B E, MOSFET = D G S B, JFET / MESFET =
 *                D G S). An empty MOSFET bulk entry ties the bulk to the source.
 */
import type { ParamDef, PartGroup, PinType, SymbolDef } from '../types';

/** Prefix of every user-component id. */
export const CUSTOM_PREFIX = 'custom:';

/** True for a web link a part may carry (http / https with a host; no other schemes). */
export function isWebLink(url: string): boolean {
  return /^https?:\/\/[^\s/?#]+[^\s]*$/i.test(url.trim());
}

export function isCustomPartId(partId: string): boolean {
  return partId.startsWith(CUSTOM_PREFIX);
}

/** Model maker ids (src/library/modelmaker). */
export type MakerId =
  | 'diode'
  | 'zener'
  | 'led'
  | 'bjt'
  | 'mosfet'
  | 'jfet'
  | 'opamp'
  | 'scr'
  | 'transformer'
  | 'tline'
  | 'acmotor';

/** The datasheet values a model was generated from (kept so the maker can be reopened). */
export interface MakerRef {
  id: MakerId;
  /** field key -> value text (user number syntax) */
  input: Record<string, string>;
}

export type CustomModel =
  | { kind: 'none' }
  | {
      kind: 'builtin';
      /** master-library part id */
      partId: string;
      /** library part pin -> symbol pin of the new part */
      pinMap: Record<string, string>;
      /** default parameter values that differ from the library part */
      params?: Record<string, string>;
      maker?: MakerRef;
    }
  | {
      kind: 'spice';
      /** `.model` / `.subckt` text (may hold several cards; dependencies are included automatically) */
      text: string;
      /** name of the model or subcircuit this part uses */
      name: string;
      /** symbol pin for each model terminal, in model order */
      pins: string[];
      maker?: MakerRef;
    };

/** Visual behaviour a user component may take over from the library. */
export interface CustomIndicator {
  /** 'led': glows with the current into model terminal 0 (the anode) */
  kind: 'led';
  /** LED colour id (src/library/parts/diodes.ts LED_COLORS) */
  color: string;
}

export interface CustomPartData {
  /** CUSTOM_PREFIX + slug */
  id: string;
  name: string;
  /** library group the part is listed under */
  group: PartGroup;
  /** family name (a built-in family or one of the database's families) */
  family: string;
  description: string;
  /** reference-designator prefix (R, D, Q, U, ...) */
  prefix: string;
  symbol: SymbolDef;
  /** parameters shown in Properties (subcircuit PARAMS: overrides for 'spice' subcircuit models) */
  params?: ParamDef[];
  model: CustomModel;
  footprint?: string;
  /** datasheet / product web page (http or https), shown as the part's hyperlink */
  hyperlink?: string;
  keywords?: string[];
  /** values of the database's user fields (manufacturer, price, supplier, ...) */
  fields?: Record<string, string>;
  provenance?: string;
  indicator?: CustomIndicator;
  /** ISO 8601 time of the last change (merging keeps the newer copy) */
  modified?: string;
  author?: string;
}

/** Which database a user component is stored in. The master database is the built-in library. */
export type DatabaseKind = 'master' | 'corporate' | 'user';

/** A user-defined family of a database. */
export interface DatabaseFamily {
  group: PartGroup;
  name: string;
}

/** A user / corporate part database (also the `.msimdb` export file format). */
export interface PartDatabase {
  format: 'machsim-partdb';
  version: 1;
  kind: Exclude<DatabaseKind, 'master'>;
  name: string;
  /** families created by the user (parts may also use built-in family names) */
  families: DatabaseFamily[];
  /** names of the user fields shown as columns in the database manager */
  fields: string[];
  parts: CustomPartData[];
  modified?: string;
}

/** A symbol exported from the symbol editor (`.msimsym` JSON file). */
export interface SymbolFile {
  format: 'machsim-symbol';
  version: 1;
  name?: string;
  symbol: SymbolDef;
}

/** Pin types offered by the pin editor (same set as PinDef.type). */
export const PIN_TYPES: PinType[] = ['passive', 'input', 'output', 'bidir', 'power', 'nc'];
