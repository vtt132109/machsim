/**
 * SHA-256, HMAC-SHA-256 and PBKDF2-HMAC-SHA-256 in plain TypeScript (FIPS 180-4, RFC 2104,
 * RFC 8018), plus hex helpers. Used for the instructor password of a design (only a salted hash is
 * stored, src/model/restrictions.ts). `pbkdf2Sha256` uses the Web Crypto API when it is available
 * (secure browser contexts, Electron, Node) and this implementation otherwise, so pages served over
 * plain http still work; both give the same bytes.
 */

