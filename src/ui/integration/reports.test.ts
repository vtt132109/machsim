import { describe, expect, it } from 'vitest';
import { buildNetlist } from '../../model/netlister';
import { runAnalyses } from '../../sim';
import { parseSpice } from '../../sim/spice';
import { circuitElements, circuitOutputs, circuitSources, specContext } from './circuitInfo';
import { commonEmitterExample, rcLowPassExample, voltageDividerExample } from './exampleDesigns';
import { designBom, designNetlistText, netlistFileName, netlistWithheld, prepareSpiceDeck } from './reports';
import { placeAutoFaults, revealFaults } from '../../model/faults';
import { getPart } from '../../library';
import { validateSpec } from '../analysis/specs';
import { setLang } from '../../i18n';

describe('designNetlistText', () => {
  it('writes a SPICE deck that parses back and simulates to the same operating point', () => {
    const design = voltageDividerExample();
    design.analysis.active = 'op';
    const report = designNetlistText(design, 'active');
    expect(report.erc).toEqual([]);
    expect(report.text.split('\n')[0]).toBe('Voltage divider + multimeter');
    // the header comment follows the UI language (Vietnamese by default)
    expect(report.text).toMatch(/^\* Voltage divider \+ multimeter — netlist do MachSim tạo$/m);
    setLang('en');
    try {
      expect(designNetlistText(design, 'active').text).toMatch(/^\* Voltage divider \+ multimeter — netlist generated by MachSim$/m);
    } finally {
      setLang('vi');
    }
    expect(report.text.trimEnd().endsWith('.end')).toBe(true);
    const parsed = parseSpice(report.text);
    expect(parsed.errors).toEqual([]);
    expect(parsed.netlist.analyses).toEqual([{ type: 'op' }]);
    const [r] = runAnalyses(parsed.netlist);
    expect(r.vectors.find((v) => v.name === 'V(OUT)')?.re[0]).toBeCloseTo(3.8367, 4);
  });

  it('can include every saved analysis or none', () => {
    const design = rcLowPassExample();
    expect(parseSpice(designNetlistText(design, 'all').text).netlist.analyses.map((a) => a.type).sort()).toEqual(['ac', 'op', 'tran']);
    expect(parseSpice(designNetlistText(design, 'none').text).netlist.analyses).toEqual([]);
  });

  it('derives the export file name', () => {
    expect(netlistFileName('C:\\work\\Amp.msim', 'x')).toBe('Amp.cir');
    expect(netlistFileName('Untitled.msim', 'My: filter')).toBe('My_ filter.cir');
  });
});

describe('designBom', () => {
  it('groups physical parts and hides virtual ones unless asked', () => {
    const bom = designBom(commonEmitterExample());
    const refs = bom.rows.flatMap((r) => r.refdes);
    expect(refs).toEqual(expect.arrayContaining(['Q1', 'R1', 'R2', 'RC', 'RE1', 'RE2', 'RL', 'CE', 'CIN', 'COUT']));
    expect(refs).not.toContain('XFG1');
    expect(bom.csv.split('\r\n')[0]).toBe('Item,Quantity,Reference,Value,Tolerance,Part,Description,Footprint');
    const caps = bom.rows.find((r) => r.refdes.includes('CIN'))!;
    expect(caps.refdes).toEqual(['CIN', 'COUT']); // same part, same value, same tolerance
    expect(caps.quantity).toBe(2);
    const rc = bom.rows.find((r) => r.refdes.includes('RC'))!;
    expect(rc.tolerance).toBe('5 %'); // the resistor's default part tolerance
    expect(designBom(commonEmitterExample(), true).rows.flatMap((r) => r.refdes)).toContain('XFG1');
  });
});

describe('prepareSpiceDeck', () => {
  it('parses a deck and adds an operating point when it has no analysis', () => {
    const deck = prepareSpiceDeck('Divider\nV1 a 0 10\nR1 a b 1k\nR2 b 0 1k\n.end\n', 'div.cir');
    expect(deck.errors).toEqual([]);
    expect(deck.title).toBe('Divider');
    expect(deck.netlist.analyses).toEqual([{ type: 'op' }]);
    expect(runAnalyses(deck.netlist)[0].vectors.find((v) => v.name === 'V(b)')?.re[0]).toBeCloseTo(5, 12);
  });

  it('reports line-numbered errors', () => {
    const deck = prepareSpiceDeck('Bad\nR1 a\n.end\n', 'bad.cir');
    expect(deck.errors.length).toBeGreaterThan(0);
    expect(deck.errors[0].line).toBe(2);
  });
});

describe('circuitInfo', () => {
  it('offers the outputs, sources and elements of a circuit to the analysis dialog', () => {
    const build = buildNetlist(commonEmitterExample(), { includeAnalysis: false });
    const outputs = circuitOutputs(build);
    expect(outputs).toEqual(expect.arrayContaining(['V(IN)', 'V(OUT)', 'V(VCC)', 'I(V_PWR_VCC)', 'I(V_XFG1_p)']));
    expect(outputs.some((o) => o.startsWith('V(0'))).toBe(false);
    expect(circuitSources(build)).toEqual(expect.arrayContaining(['V_PWR_VCC', 'V_XFG1_p']));
    const els = circuitElements(build);
    // RC = 4.7 kΩ from VCC to the collector, default 5 % part tolerance
    expect(els.find((e) => e.name === 'RC')).toEqual({ name: 'RC', type: 'R', nodes: ['VCC', build.partNets.RC['2']], hasValue: true, value: 4700, params: [], tol: 0.05 });
    // the function generator's sine-only source: no DC "value", its waveform parameters instead
    const fg = els.find((e) => e.name === 'V_XFG1_p')!;
    expect(fg.hasValue).toBe(false);
    expect(fg.signal).toBe(true);
    expect(fg.params).toEqual(expect.arrayContaining(['va', 'freq']));
    expect(els.find((e) => e.name === 'V_PWR_VCC')).toMatchObject({ hasValue: true, value: 12, signal: false });
    expect(els.some((e) => e.model && /3904/i.test(e.name) && e.params!.includes('bf'))).toBe(true);
    // the saved specs of the example validate against this context
    const ctx = specContext(build);
    for (const spec of Object.values(commonEmitterExample().analysis.specs)) {
      expect(validateSpec(spec!, ctx).filter((i) => i.severity === 'error')).toEqual([]);
    }
  });
});

describe('hidden auto faults', () => {
  it('withhold the netlist listing until the faults are revealed, and stay out of the analysis lists', () => {
    const { design } = placeAutoFaults(voltageDividerExample(), getPart, { count: 2, seed: 3 });
    expect(netlistWithheld(design)).toBe('faults');
    const report = designNetlistText(design, 'all');
    expect(report.withheld).toBe('faults');
    expect(report.elementCount).toBe(0);
    expect(report.text.trim().split('\n')).toHaveLength(3);
    expect(report.text).not.toMatch(/_f[osl]_|R_HF_/i);
    // the analysis dialogs list neither the fault resistors nor their private nodes
    const build = buildNetlist(design);
    expect(circuitElements(build).map((e) => e.name).filter((n) => /HF/.test(n))).toEqual([]);
    expect(circuitOutputs(build).filter((o) => /_f[osl]_/i.test(o))).toEqual([]);
    // after Reveal faults the listing is complete again and names them
    const shown = designNetlistText(revealFaults(design), 'none');
    expect(shown.withheld).toBeUndefined();
    expect(shown.text).toMatch(/_f[osl]_/i);
  });
});
