/**
 * The Netlist tab lists model parameters with 6 significant digits, while exported netlists stay
 * exact (read back bit-for-bit) and the simulation is unaffected.
 */
import { describe, expect, it } from 'vitest';
import { DesignBuilder } from '../../model/designkit';
import { buildNetlist } from '../../model/netlister';
import { parseSpice, writeSpice } from '../../sim/spice';
import { setLang } from '../../i18n';
import { designNetlistText } from './reports';

setLang('en');

function ledDesign() {
  const b = new DesignBuilder('LED');
  const v = b.part('sources/dc-voltage', 'V1', 0, 0, { value: '5' });
  b.part('sources/ground', 'GND1', 0, 100);
  const r = b.part('basic/resistor', 'R1', 100, 0, { value: '220' });
  const d = b.part('diodes/led-red', 'LED1', 200, 0, {});
  b.wire(b.pin(v, '+'), b.pin(r, '1'));
  b.wire(b.pin(r, '2'), b.pin(d, 'A'));
  b.wire(b.pin(d, 'K'), { x: 0, y: 100 });
  b.wire(b.pin(v, '-'), { x: 0, y: 100 });
  return b.design;
}

const LONG_NUMBER = /\d\.\d{7,}/;

describe('netlist number formatting', () => {
  it('rounds the listing to 6 significant digits', () => {
    const exact = designNetlistText(ledDesign()).text;
    const listing = designNetlistText(ledDesign(), 'active', { digits: 6 }).text;
    expect(exact).toMatch(LONG_NUMBER);
    expect(listing).not.toMatch(LONG_NUMBER);
    const is = listing.match(/\bis=([^\s)]+)/i);
    expect(is).not.toBeNull();
    expect(is![1].replace(/e-?\d+$/, '').replace(/[a-z]+$/i, '').replace('-', '').replace('.', '').length).toBeLessThanOrEqual(6);
    expect(listing).toContain('* LED — netlist generated by MachSim');
  });

  it('keeps exported text exact and the IR unchanged', () => {
    const build = buildNetlist(ledDesign());
    const before = JSON.stringify(build.netlist.models);
    writeSpice(build.netlist, { digits: 6 });
    expect(JSON.stringify(build.netlist.models)).toBe(before);
    const back = parseSpice(writeSpice(build.netlist), { hasTitle: true }).netlist;
    for (const [name, card] of Object.entries(build.netlist.models)) expect(back.models[name.toLowerCase()]?.params ?? back.models[name]?.params).toEqual(card.params);
  });
});
